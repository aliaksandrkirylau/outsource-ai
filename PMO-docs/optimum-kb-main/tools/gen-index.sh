#!/bin/sh
# Rebuild index.md from the frontmatter of every note under the knowledge folder.
# Usage: sh tools/gen-index.sh [output-file]   (default index.md)
# Links are wikilinks by note name, so note names must be unique (kb-lint checks).
cd "$(dirname "$0")/.." || exit 1
KB_DIR=${KB_DIR:-knowledge}
TYPES="capability requirement concern decision question term commitment increment risk"
out=${1:-index.md}
tmp=$(mktemp)
[ -d "$KB_DIR" ] && find "$KB_DIR" -name '*.md' ! -name AGENTS.md | sort | while read -r f; do
  awk -v f="$f" '
    { sub(/\r$/, "") }
    NR == 1 && $0 != "---" { exit }
    NR > 1 && $0 == "---" { exit }
    /^type:/        { t = $2 }
    /^status:/      { s = $2 }
    /^scope_status:/ { sc = $2 }
    /^answered_by:/ { a = $2 }
    /^critical:/     { cr = $2 }
    END { n = f; sub(/^.*\//, "", n); sub(/\.md$/, "", n); if (t != "") print t "\t" n "\t" s "\t" (a != "" ? "answered" : "open") "\t" sc "\t" cr }' "$f"
done > "$tmp"
{
  echo "# Index"
  echo
  echo "Generated by tools/gen-index.sh - do not edit by hand."
  echo "Notes: $(wc -l < "$tmp" | tr -d ' ')"
  echo
  echo "## Needs a decision"
  echo
  echo "Disputed notes:"
  echo
  awk -F '\t' '$3 == "disputed" { print "- [[" $2 "]]" }' "$tmp"
  echo
  echo "Open questions:"
  echo
  awk -F '\t' '$1 == "question" && $4 == "open" && $3 != "deprecated" { print "- [[" $2 "]] - " $3 }' "$tmp"
  echo
  echo "Change request candidates (proposed-change requirements):"
  echo
  awk -F '\t' '$1 == "requirement" && $5 == "proposed-change" && $3 != "deprecated" { print "- [[" $2 "]] - " $3 }' "$tmp"
  echo
  echo "Open critical risks:"
  echo
  awk -F '\t' '$1 == "risk" && $6 == "yes" && $3 != "deprecated" { print "- [[" $2 "]] - " $3 }' "$tmp"
  for t in $TYPES; do
    echo
    case $t in capability) h=capabilities ;; *) h="${t}s" ;; esac
    echo "## $h"
    echo
    awk -F '\t' -v t="$t" '$1 == t { print "- [[" $2 "]] - " $3 }' "$tmp"
  done
} > "$out"
rm -f "$tmp"
